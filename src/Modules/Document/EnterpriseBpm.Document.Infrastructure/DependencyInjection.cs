using EnterpriseBpm.Document.Application.Contracts;
using EnterpriseBpm.Document.Application.Handlers;
using EnterpriseBpm.Document.Infrastructure.Persistence;
using EnterpriseBpm.Document.Infrastructure.Services;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;

namespace EnterpriseBpm.Document.Infrastructure;

public static class DependencyInjection
{
    public static IServiceCollection AddDocumentInfrastructure(
        this IServiceCollection services,
        IConfiguration configuration)
    {
        var connectionString = configuration.GetConnectionString("DefaultConnection")
            ?? throw new InvalidOperationException("Chuỗi kết nối cơ sở dữ liệu 'DefaultConnection' chưa được cấu hình trong hệ thống.");

        services.AddDbContextPool<DocumentDbContext>(options =>
            options.UseSqlServer(connectionString, sqlOptions =>
            {
                sqlOptions.MigrationsHistoryTable("__EFMigrationsHistory", "document");
                sqlOptions.EnableRetryOnFailure(3);
            }), poolSize: 256);

        services.AddScoped<IDocumentDbContextProvider>(sp => sp.GetRequiredService<DocumentDbContext>());

        // Storage & Services
        services.AddSingleton<IExternalStorageClient, ExternalStorageClient>();
        services.AddScoped<IDocumentStorageService, DocumentStorageService>();
        services.AddScoped<IDocumentTemplateService, DocumentTemplateService>();
        services.AddScoped<IDocumentGeneratorService, DocumentGeneratorService>();

        // MediatR
        services.AddMediatR(cfg =>
        {
            cfg.RegisterServicesFromAssembly(typeof(AutoGenerateDocumentOnApprovalHandler).Assembly);
        });

        return services;
    }
}

