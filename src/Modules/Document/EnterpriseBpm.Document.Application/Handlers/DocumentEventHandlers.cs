using EnterpriseBpm.Document.Application.Contracts;
using EnterpriseBpm.Document.Domain.Entities;
using EnterpriseBpm.Workflow.Application.Events;
using MediatR;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace EnterpriseBpm.Document.Application.Handlers;

public interface IDocumentDbContextProvider
{
    DbSet<WorkflowAttachment> WorkflowAttachments { get; }
    DbSet<DocumentTemplate> DocumentTemplates { get; }
    DbSet<GeneratedDocument> GeneratedDocuments { get; }
    Task<int> SaveChangesAsync(CancellationToken cancellationToken = default);
}

/// <summary>
/// Lắng nghe WorkflowApprovedEvent: Tự động sinh văn bản (Quyết định, Hợp đồng) khi quy trình được duyệt hoàn tất.
/// </summary>
public class AutoGenerateDocumentOnApprovalHandler : INotificationHandler<WorkflowApprovedEvent>
{
    private readonly IDocumentDbContextProvider _dbContext;
    private readonly IDocumentGeneratorService _generatorService;
    private readonly ILogger<AutoGenerateDocumentOnApprovalHandler> _logger;

    public AutoGenerateDocumentOnApprovalHandler(
        IDocumentDbContextProvider dbContext,
        IDocumentGeneratorService generatorService,
        ILogger<AutoGenerateDocumentOnApprovalHandler> logger)
    {
        _dbContext = dbContext;
        _generatorService = generatorService;
        _logger = logger;
    }

    public async Task Handle(WorkflowApprovedEvent notification, CancellationToken cancellationToken)
    {
        _logger.LogInformation(
            "Tiếp nhận WorkflowApprovedEvent cho Instance {InstanceId}, FormKey: {FormKey}. Kiểm tra mẫu văn bản tự động sinh.",
            notification.WorkflowInstanceId, notification.FormKey);

        // Quy ước mẫu tài liệu: thử "tpl_{FormKey}" trước, nếu không có thì fallback sang "tpl_default"
        var expectedTemplateKey = $"tpl_{notification.FormKey.ToLowerInvariant()}";
        var template = await _dbContext.DocumentTemplates
            .FirstOrDefaultAsync(t => (t.TemplateKey == expectedTemplateKey || t.TemplateKey == "tpl_default") && t.IsActive, cancellationToken);

        if (template == null)
        {
            _logger.LogInformation("Không có mẫu văn bản tự động sinh nào được cấu hình cho {TemplateKey}.", expectedTemplateKey);
            return;
        }

        var placeholderData = new Dictionary<string, object>
        {
            { "FormKey", notification.FormKey },
            { "WorkflowInstanceId", notification.WorkflowInstanceId },
            { "ApprovedByUserId", notification.ApprovedByUserId },
            { "ApprovedAt", notification.ApprovedAt.ToString("dd/MM/yyyy HH:mm") }
        };

        try
        {
            var generated = await _generatorService.GenerateFromTemplateAsync(
                templateKey: template.TemplateKey,
                workflowInstanceId: notification.WorkflowInstanceId,
                placeholderValues: placeholderData,
                generatedByUserId: notification.ApprovedByUserId,
                cancellationToken: cancellationToken);

            _logger.LogInformation(
                "Đã tự động sinh thành công văn bản {FileName} cho Instance {InstanceId}.",
                generated.GeneratedFileName, notification.WorkflowInstanceId);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Lỗi xảy ra trong quá trình tự động sinh văn bản cho Instance {InstanceId}.", notification.WorkflowInstanceId);
        }
    }
}

/// <summary>
/// Lắng nghe WorkflowCancelledEvent: Tự động đánh dấu xóa mềm các file đính kèm của quy trình bị hủy.
/// </summary>
public class HandleDocumentOnWorkflowCancelledHandler : INotificationHandler<WorkflowCancelledEvent>
{
    private readonly IDocumentDbContextProvider _dbContext;
    private readonly ILogger<HandleDocumentOnWorkflowCancelledHandler> _logger;

    public HandleDocumentOnWorkflowCancelledHandler(
        IDocumentDbContextProvider dbContext,
        ILogger<HandleDocumentOnWorkflowCancelledHandler> logger)
    {
        _dbContext = dbContext;
        _logger = logger;
    }

    public async Task Handle(WorkflowCancelledEvent notification, CancellationToken cancellationToken)
    {
        _logger.LogInformation(
            "Tiếp nhận WorkflowCancelledEvent cho Instance {InstanceId}. Bắt đầu dọn dẹp các tệp đính kèm liên quan.",
            notification.WorkflowInstanceId);

        var attachments = await _dbContext.WorkflowAttachments
            .Where(a => a.WorkflowInstanceId == notification.WorkflowInstanceId && a.DeletedAt == null)
            .ToListAsync(cancellationToken);

        if (attachments.Count == 0) return;

        foreach (var attachment in attachments)
        {
            attachment.MarkDeleted(notification.CancelledByUserId);
        }

        await _dbContext.SaveChangesAsync(cancellationToken);
        _logger.LogInformation("Đã đánh dấu xóa mềm {Count} tệp đính kèm của Instance {InstanceId}.", attachments.Count, notification.WorkflowInstanceId);
    }
}

